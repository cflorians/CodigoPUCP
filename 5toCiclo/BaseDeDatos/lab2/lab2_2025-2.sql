WHERE b.PACIENTE_ID = p.PACIENTE_ID
ORDER BY FECHA_EMISION DESC;

-- Pregunta 6

SELECT e.DENOMINACION, COUNT(*) AS CANT_SERVICIOS, MIN(s.PRECIO) AS PRECIO_MIN, MAX(s.PRECIO) AS PRECIO_MAX, AVG(s.PRECIO) AS PRECIO_PROM
FROM ESPECIALIDADES e
INNER JOIN SERVICIOS_MEDICOS s ON e.ESPECIALIDAD_ID = s.ESPECIALIDAD_ID
GROUP BY e.DENOMINACION
ORDER BY PRECIO_PROM DESC;

-- Pregunta 7

SELECT e.DENOMINACION, 
       COUNT(*) AS ATENCIONES, 
       ROUND(MIN((a.HORA_FIN - a.HORA_INICIO)*24*60),1) AS MIN_MINUTOS,
       ROUND(MAX((a.HORA_FIN - a.HORA_INICIO)*24*60),1) AS MAX_MINUTOS,
       ROUND(AVG((a.HORA_FIN - a.HORA_INICIO)*24*60),1) AS AVG_MINUTOS
FROM ESPECIALIDADES e
INNER JOIN PERSONALES_MEDICOS p ON e.ESPECIALIDAD_ID = p.ESPECIALIDAD_ID
INNER JOIN ATENCIONES_MEDICAS a ON p.PERSONAL_ID = a.PERSONAL_ID
GROUP BY e.DENOMINACION
ORDER BY AVG_MINUTOS DESC;

-- Pregunta 8

SELECT p.PACIENTE_ID, (p.NOMBRE || ' ' || p.PRIMER_APELLIDO || ' ' || p.SEGUNDO_APELLIDO) AS PACIENTE, SUM(b.MONTO_TOTAL) AS MONTO_TOTAL
FROM PACIENTES p
INNER JOIN BOLETAS b ON b.PACIENTE_ID = p.PACIENTE_ID
GROUP BY p.PACIENTE_ID, (p.NOMBRE || ' ' || p.PRIMER_APELLIDO || ' ' || p.SEGUNDO_APELLIDO)
ORDER BY MONTO_TOTAL DESC;

-- Pregunta 9

SELECT m.MEDICAMENTO_ID, m.DENOMINACION, SUM(b.CANTIDAD) AS CANTIDAD_VENDIDA, SUM(b.SUBTOTAL) AS MONTO_VENDIDO
FROM MEDICAMENTOS m
INNER JOIN BOLETAS_MEDICAMENTOS b ON m.MEDICAMENTO_ID = b.MEDICAMENTO_ID
GROUP BY m.MEDICAMENTO_ID, m.DENOMINACION
ORDER BY CANTIDAD_VENDIDA DESC
