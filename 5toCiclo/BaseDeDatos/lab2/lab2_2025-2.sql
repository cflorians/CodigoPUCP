SELECT b.NRO_SERIE, b.FECHA_EMISION, (p.NOMBRE || ' ' || p.PRIMER_APELLIDO || ' ' || p.SEGUNDO_APELLIDO) AS PACIENTE , b.MONTO_TOTAL
