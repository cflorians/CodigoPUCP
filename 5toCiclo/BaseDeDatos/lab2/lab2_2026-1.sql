-- Pregunta 2

SELECT f.MODELO_ID, mod.DESCRIPCION, d.FICHA_ID, f.VERSION, f.DESCRIPCION, d.TALLA, d.CANTIDAD_POR_PAR
FROM ALM_MATERIAS_PRIMAS m
INNER JOIN CAT_DETALLES_FICHAS d ON m.MATERIA_PRIMA_ID = d.MATERIA_PRIMA_ID
INNER JOIN CAT_FICHAS_TECNICAS f ON f.FICHA_ID = d.FICHA_ID
INNER JOIN CAT_MODELOS mod ON mod.MODELO_ID = f.MODELO_ID
WHERE mod.TIPO_CALZADO = 'BOTA';

-- Pregunta 3

SELECT o.ORDEN_PROD_ID, o.CODIGO, o.FECHA_EMISION, ROUND(SUM(m.COSTO_UNIT_PROMEDIO*r.CANTIDAD_TEORICA),2) AS COSTO_ORDEN
FROM PRD_ORDENES_PRODUCCION o
INNER JOIN PRD_REQUERIMIENTOS_MAT r ON r.ORDEN_PROD_ID = o.ORDEN_PROD_ID
INNER JOIN ALM_MATERIAS_PRIMAS m ON m.MATERIA_PRIMA_ID = r.MATERIA_PRIMA_ID
WHERE EXTRACT(MONTH FROM o.FECHA_EMISION) = 4 AND EXTRACT(YEAR FROM o.FECHA_EMISION) = 2026 AND o.ESTADO IN ('EN_PRODUCCION', 'COMPLETADA', 'PLANIFICADA')
GROUP BY o.ORDEN_PROD_ID, o.CODIGO, o.FECHA_EMISION
ORDER BY COSTO_ORDEN DESC;

