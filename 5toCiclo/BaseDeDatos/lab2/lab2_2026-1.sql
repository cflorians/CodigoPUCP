CREATE OR REPLACE VIEW VM_ENTRADAS AS
SELECT MATERIA_PRIMA_ID, SUM(CANTIDAD) AS CANT_ENTRADAS
FROM ALM_MOVIMIENTOS
WHERE TIPO_MOVIMIENTO = 'ENTRADA'
GROUP BY MATERIA_PRIMA_ID;
