public class Principal {
    // public + (main + TAB)
    public static void main(String[] args) {
        // Tipos de datos java
        // sout + TAB
        // soutv + TAB
        int numero = 45784;
        long numeroGrande = 839480797;
        System.out.println("Numero = " + numero);
        System.out.println("NumeroGrande = " + numeroGrande);

        float realPequeno = 78452.25f; // se debe colocar f al final del numero
        double realGran = 223784924.456;
        System.out.println("RealPequeno = " + realPequeno);
        System.out.println("RealGrande = " + realGran);

        char letra = 'm';
        String nombre = "Carlos";
        System.out.println("Letra = " + letra);
        System.out.println("Nombre = " + nombre);
    }
}
